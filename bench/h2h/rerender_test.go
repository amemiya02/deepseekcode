package h2h

import (
	"encoding/json"
	"os"
	"path/filepath"
	"testing"
)

// TestReRenderH2HReport loads the benchmark JSON data and re-renders the
// report through RenderReport, saving the output to the docs readout path.
func TestReRenderH2HReport(t *testing.T) {
	dataPath := filepath.Join("..", "..", "docs", "internal", "competitive", "data", "h2h-2026-06-10.json")
	raw, err := os.ReadFile(dataPath)
	if err != nil {
		t.Skipf("data file not found: %v", err)
	}

	var rr RunResult
	if err := json.Unmarshal(raw, &rr); err != nil {
		t.Fatalf("unmarshal: %v", err)
	}

	report := RenderReport(rr)
	if report == "" {
		t.Fatal("RenderReport returned empty string")
	}

	outDir := filepath.Join("..", "..", "docs", "internal", "competitive")
	outPath := filepath.Join(outDir, "2026-06-11-h2h-deconfounded-readout.md")

	// Prepend a header noting this is a re-render.
	header := "<!-- auto-generated by TestReRenderH2HReport — do not edit by hand -->\n\n"
	content := header + report

	if err := os.WriteFile(outPath, []byte(content), 0o644); err != nil {
		t.Fatalf("write report: %v", err)
	}

	t.Logf("wrote %d bytes to %s", len(content), outPath)
}
